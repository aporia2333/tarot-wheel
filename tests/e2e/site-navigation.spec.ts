import { expect, test } from "@playwright/test";

test("one header keeps skin, dealer and account controls usable and remembers the dealer across pages", async ({ page }) => {
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto("/design-preview?view=motion");
  const header = page.locator(".site-header");
  const skinMenu = header.locator("summary").filter({ hasText:"牌面选择" });
  const accountMenu = header.locator("summary").filter({ hasText:"账号" });
  const dealer = header.getByRole("button", { name:"占卜师选择", exact:true });
  await expect(page.locator("nav")).toHaveCount(1);
  await dealer.click(); await page.getByRole("button", { name:"曲奇猫", exact:true }).click();
  await expect(page.locator(".preparation-scene")).toHaveAttribute("data-character", "quqi");
  await skinMenu.click();
  await page.getByRole("combobox", { name:"牌面皮肤", exact:true }).selectOption("quqi");
  await expect(page.locator("g[data-packet] image")).toHaveAttribute("href", /quqi/);
  await accountMenu.click();
  await expect(header.locator("details[open]")).toHaveCount(1);
  await expect(page.getByText("本地体验模式", { exact:true })).toBeVisible();
  await accountMenu.press("Escape");
  await expect(header.locator("details[open]")).toHaveCount(0);
  await expect(accountMenu).toBeFocused();
  await page.getByRole("button", { name:"播放洗牌", exact:true }).click();
  await expect(dealer).toBeDisabled();
  await expect(dealer).toBeEnabled({ timeout:10_000 });
  await dealer.click(); await page.getByRole("button", { name:"星帽猫", exact:true }).click();
  await page.getByRole("link", { name:"星月之间首页", exact:true }).click();
  await expect(page).toHaveURL("http://127.0.0.1:3100/");
  await expect(page.getByRole("heading", { name:"星月之间", exact:true })).toBeVisible();
  await page.reload(); await dealer.click();
  await expect(page.getByRole("button", { name:"星帽猫", exact:true })).toHaveAttribute("aria-pressed", "true");
  await page.keyboard.press("Escape"); await expect(dealer).toBeFocused();
  await header.getByRole("link", { name:"历史记录", exact:true }).click();
  await expect(page).toHaveURL(/\/history$/);
  await expect(header.getByRole("link", { name:"历史记录", exact:true })).toHaveAttribute("aria-current", "page");
  await accountMenu.click(); await page.getByRole("link", { name:"账号说明", exact:true }).click();
  await expect(page).toHaveURL(/\/account$/);
  await expect(header.locator("details[open]")).toHaveCount(0);
  expect(errors).toEqual([]);
});
